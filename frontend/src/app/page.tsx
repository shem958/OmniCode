// Mermaid Dynamic Renderer
const MermaidRenderer = ({ code }: { code: string }) => {
  const containerRef = useRef<HTMLDivElement>(null);
  const [svg, setSvg] = useState<string>("");
  const [error, setError] = useState<string>("");

  useEffect(() => {
    if (!code) return;
    
    // Dynamic import to avoid SSR errors
    import("mermaid").then((mermaid) => {
      mermaid.default.initialize({
        startOnLoad: false,
        theme: "dark",
        securityLevel: "loose",
        flowchart: { useMaxWidth: true, htmlLabels: true }
      });
      
      const renderId = `mermaid-${Math.floor(Math.random() * 100000)}`;
      try {
        mermaid.default.render(renderId, code).then(({ svg }) => {
          setSvg(svg);
          setError("");
        }).catch((err) => {
          console.error("Mermaid Render Error", err);
          setError("Invalid Diagram Syntax generated by LLM.");
        });
      } catch (err) {
        setError("Mermaid Render Exception.");
      }
    });
  }, [code]);

  if (error) {
    return (
      <div className="p-4 bg-red-950/40 border border-red-800/80 rounded-lg text-red-300 text-sm">
        <AlertTriangle className="h-5 w-5 inline mr-2 text-red-400" />
        {error}
        <pre className="mt-2 text-xs font-mono bg-black/30 p-2 rounded overflow-auto">{code}</pre>
      </div>
    );
  }

  return (
    <div className="flex justify-center bg-zinc-950 p-4 border border-zinc-800 rounded-xl overflow-auto w-full max-h-[500px]">
      {svg ? (
        <div ref={containerRef} dangerouslySetInnerHTML={{ __html: svg }} />
      ) : (
        <div className="text-zinc-500 text-sm animate-pulse">Rendering diagram...</div>
      )}
    </div>
  );
};

